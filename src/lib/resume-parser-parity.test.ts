import { describe, expect, it } from 'vitest';
import { parseResumeMarkdown } from '@/lib/resume-parser';
import serverFixtures from '@/lib/__fixtures__/server-parser.json';

/**
 * The client parser must agree with the server parser.
 *
 * # Why this test is the point of the whole ticket
 *
 * ADR-0003 keeps two parsers: the server's is authoritative, and the editor keeps one for
 * live preview because it cannot round-trip on every keystroke. A duplicated parser drifts,
 * and this particular drift is **invisible**: the preview renders fine, and the difference
 * only shows after a save, when the saved view draws the document a different way. No type
 * check or unit test on either parser alone can see it.
 *
 * So the duplication is allowed only because it is *verified*. `server-parser.json` is the
 * server parser's own output, generated by
 * `kratos-server/cmd/resumefixtures` (run it to regenerate; the corpus lives there with a
 * note on what each document pins). This test replays the same documents through the client
 * parser and fails if the two disagree at all.
 *
 * A failure here means one side changed and the other did not. Work out which is right
 * **against ADR-0003 and the Go implementation**, fix that side, and regenerate the fixture
 * if the Go side moved.
 *
 * # What "agree" means
 *
 * Every section: title, kind, content, and its items in order. Every item: title, subtitle,
 * date, details in order. Field-by-field rather than a whole-object comparison so a failure
 * names the document and the field instead of printing two large objects.
 */

interface ServerItem {
  title?: string;
  subtitle?: string;
  date?: string;
  details?: string[];
}

interface ServerSection {
  title?: string;
  kind?: string;
  content?: string;
  items?: ServerItem[];
}

interface ServerFixture {
  id: string;
  why: string;
  markdown: string;
  sections: ServerSection[];
}

const fixtures = serverFixtures as ServerFixture[];

/** Running record of the first difference found, so a failure is actionable. */
function describeDiff(
  id: string,
  path: string,
  field: string,
  expected: unknown,
  actual: unknown,
): string {
  return [
    `parity mismatch in fixture "${id}"`,
    `  at:    ${path}`,
    `  field: ${field}`,
    `  server (expected): ${JSON.stringify(expected)}`,
    `  client (actual):   ${JSON.stringify(actual)}`,
  ].join('\n');
}

describe('client parser agrees with the server parser (ticket 18, ADR-0003)', () => {
  it('has a corpus worth checking', () => {
    // Guards the test itself: an empty or truncated fixture file would make every assertion
    // below vacuous and the suite would stay green while checking nothing.
    expect(fixtures.length).toBeGreaterThan(10);
    expect(fixtures.every((f) => typeof f.id === 'string' && f.id !== '')).toBe(true);
    expect(fixtures.some((f) => (f.sections?.length ?? 0) > 1)).toBe(true);
    expect(fixtures.some((f) => (f.sections?.length ?? 0) === 0)).toBe(true);
  });

  for (const fixture of fixtures) {
    it(`agrees on "${fixture.id}" — ${fixture.why}`, () => {
      const actual = parseResumeMarkdown(fixture.markdown);
      const expected = fixture.sections ?? [];

      expect(
        actual.sections.length,
        `section count differs for "${fixture.id}"\n  server: ${expected
          .map((s) => s.title)
          .join(', ')}\n  client: ${actual.sections.map((s) => s.title).join(', ')}`,
      ).toBe(expected.length);

      expected.forEach((expectedSection, si) => {
        const actualSection = actual.sections[si];
        const where = `section ${si} (${expectedSection.title})`;

        for (const field of ['title', 'kind', 'content'] as const) {
          const want = expectedSection[field] ?? '';
          const got = actualSection[field] ?? '';
          if (want !== got) {
            throw new Error(describeDiff(fixture.id, where, field, want, got));
          }
        }

        const expectedItems = expectedSection.items ?? [];
        const actualItems = actualSection.items ?? [];
        expect(
          actualItems.length,
          `item count differs in ${where} of "${fixture.id}"`,
        ).toBe(expectedItems.length);

        expectedItems.forEach((expectedItem, ii) => {
          const actualItem = actualItems[ii];
          const itemWhere = `${where} → item ${ii} (${expectedItem.title})`;

          for (const field of ['title', 'subtitle', 'date'] as const) {
            const want = expectedItem[field] ?? '';
            const got = actualItem[field] ?? '';
            if (want !== got) {
              throw new Error(describeDiff(fixture.id, itemWhere, field, want, got));
            }
          }

          const wantDetails = expectedItem.details ?? [];
          const gotDetails = actualItem.details ?? [];
          if (JSON.stringify(wantDetails) !== JSON.stringify(gotDetails)) {
            throw new Error(
              describeDiff(fixture.id, itemWhere, 'details', wantDetails, gotDetails),
            );
          }
        });
      });
    });
  }

  it('does not leave a stray carriage return in any parsed field', () => {
    // Every document on disk is CRLF, and a `\r` that survives into a detail or a date is
    // invisible on screen but corrupts the value (and any later comparison). The fixture's
    // CRLF document exercises the path; this asserts the property directly for all of them.
    for (const fixture of fixtures) {
      const { sections } = parseResumeMarkdown(fixture.markdown);
      const serialised = JSON.stringify(sections);
      expect(serialised.includes('\\r'), `"${fixture.id}" produced a \\r`).toBe(false);
    }
  });
});
